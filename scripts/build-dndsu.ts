function spell(
  ru: string,
  en: string,
  path: string,
  book: string,
  bookRu: string,
  text: string,
  fields: Partial<Spell["spell"]>,
) {
  const defaults = {
    level: 0,
    school: "Evocation",
    castingTime: "Action",
    castingTimeRu: "Одно действие",
    rangeFeet: 0,
    rangeKind: "Self",
    rangeRu: "На себя",
    targetRu: "",
    components: ["S"],
    materialComponentRu: "",
    durationRu: "Один раунд",
    classes: ["Волшебник", "Изобретатель", "Колдун", "Чародей"],
  };
  const parsed = datasetSchema.parse({
    schemaVersion: 1,
    name: "Проверка",
    sources: [],
    entries: [
      {
        ...base(2014, ru, en, `spells/${path}/`, book, bookRu, text),
        kind: "Spell",
        spell: { ...defaults, ...fields },
      },
    ],
  });
  entries.push(parsed.entries[0]);
}
