function base(
  year: 2014 | 2024,
  nameRu: string,
  nameOriginal: string,
  path: string,
  book: string,
  bookRu: string,
  descriptionRu: string,
) {
  const edition = `5e_${year}` as const;
  books.set(`${year}:${book}`, { ru: bookRu, original: book });
  return {
    id: uuid(`${year}:${path}`),
    nameRu,
    nameOriginal,
    descriptionRu,
    descriptionOriginal: "",
    edition,
    sourceBookId: uuid(`${year}:${book}`),
    source: `https://${year === 2024 ? "next." : ""}dnd.su/${path}`,
    sourcePage: "",
    license,
    rulesVersion: String(year),
    translationStatus: "Approved" as const,
    contentOrigin: "MetadataOnly" as const,
    aliases: [],
    tags: ["Дополнение по DnD.su", "Краткая сводка"],
    contentVersion: 1,
    errataVersion: "",
    createdAt: date,
    updatedAt: date,
  };
}
